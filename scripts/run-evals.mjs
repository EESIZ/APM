import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(scriptDir, "..");
const evalPath = path.join(root, "evals", "evals.json");
const skillPath = path.join(root, "SKILL.md");
const resultsDir = path.join(root, "evals", "results");
const latestPath = path.join(resultsDir, "latest.json");
const reportPath = path.join(root, "evals", "RESULTS.md");

function parseArgs(argv) {
  const options = { verify: false, limit: null };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--verify") options.verify = true;
    else if (arg === "--runtime") options.runtime = argv[++index];
    else if (arg === "--model") options.model = argv[++index];
    else if (arg === "--judge-model") options.judgeModel = argv[++index];
    else if (arg === "--max-budget-usd") options.maxBudgetUsd = argv[++index];
    else if (arg === "--limit") options.limit = Number.parseInt(argv[++index], 10);
    else throw new Error(`unknown argument: ${arg}`);
  }
  if (options.limit !== null && (!Number.isInteger(options.limit) || options.limit < 1)) {
    throw new Error("--limit must be a positive integer");
  }
  if (options.runtime && !["claude", "codex"].includes(options.runtime)) {
    throw new Error("--runtime must be claude or codex");
  }
  return options;
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function hashFile(filePath) {
  return crypto.createHash("sha256").update(fs.readFileSync(filePath)).digest("hex");
}

function fail(message) {
  console.error(`evaluation verification failed: ${message}`);
  process.exit(1);
}

function verifyResults() {
  if (!fs.existsSync(latestPath)) fail("evals/results/latest.json is missing; run npm run eval");
  if (!fs.existsSync(reportPath)) fail("evals/RESULTS.md is missing; run npm run eval");

  const suite = readJson(evalPath);
  const result = readJson(latestPath);
  const dimensions = Object.keys(suite.rubric.dimensions);

  if (result.schema_version !== 1) fail("unsupported result schema");
  if (result.suite_sha256 !== hashFile(evalPath)) fail("evaluation suite changed after the latest run");
  if (result.skill_sha256 !== hashFile(skillPath)) fail("SKILL.md changed after the latest run");
  if (result.cases.length !== suite.evals.length) fail("latest run does not cover the full suite");
  if (!result.comparison?.same_target_model || !result.comparison?.blind_judge) fail("comparison controls are incomplete");

  for (const item of result.cases) {
    if (typeof item.no_skill?.output !== "string" || !item.no_skill.output.trim()) fail(`${item.id} has no baseline output`);
    if (typeof item.apm?.output !== "string" || !item.apm.output.trim()) fail(`${item.id} has no APM output`);
    for (const condition of ["no_skill", "apm"]) {
      for (const dimension of dimensions) {
        const score = item.scores?.[condition]?.[dimension];
        if (!Number.isInteger(score) || score < 0 || score > 4) {
          fail(`${item.id} has invalid ${condition}.${dimension} score`);
        }
      }
    }
  }

  const report = fs.readFileSync(reportPath, "utf8");
  if (!report.includes("<!-- generated by scripts/run-evals.mjs -->")) fail("RESULTS.md is not generated by the harness");
  console.log("evaluation verification passed");
}

function runClaude({ cli, cwd, prompt, model, maxBudgetUsd, systemPrompt, schema }) {
  const args = [
    "-p",
    "--disable-slash-commands",
    "--tools",
    "",
    "--permission-mode",
    "dontAsk",
    "--no-session-persistence",
    "--output-format",
    "json",
    "--model",
    model,
    "--effort",
    "low",
    "--max-budget-usd",
    String(maxBudgetUsd)
  ];

  if (systemPrompt) args.push("--append-system-prompt", systemPrompt);
  if (schema) args.push("--json-schema", JSON.stringify(schema));

  const startedAt = Date.now();
  const execution = spawnSync(cli, args, {
    cwd,
    input: prompt,
    encoding: "utf8",
    windowsHide: true,
    timeout: 240000,
    maxBuffer: 8 * 1024 * 1024,
    env: {
      ...process.env,
      CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC: "1"
    }
  });

  if (execution.error) throw new Error(`claude invocation failed: ${execution.error.message}`);
  if (execution.status !== 0) {
    throw new Error(`claude exited ${execution.status}: ${(execution.stderr || execution.stdout).trim()}`);
  }

  let envelope;
  try {
    envelope = JSON.parse(execution.stdout);
  } catch {
    throw new Error(`claude returned non-JSON output: ${execution.stdout.slice(0, 500)}`);
  }

  const output = envelope.structured_output ?? envelope.result;
  if (output === undefined || output === null) throw new Error("claude JSON contains no result");

  return {
    output: typeof output === "string" ? output : JSON.stringify(output),
    structured: envelope.structured_output ?? null,
    model: envelope.model ?? model,
    requested_model: model,
    duration_ms: Date.now() - startedAt,
    cost_usd: envelope.total_cost_usd ?? null,
    usage: envelope.usage ?? null
  };
}

function runCodex({ cli, cwd, prompt, model, schema }) {
  const outputFile = path.join(cwd, `.codex-output-${crypto.randomUUID()}.txt`);
  const schemaFile = schema ? path.join(cwd, `.codex-schema-${crypto.randomUUID()}.json`) : null;
  if (schemaFile) fs.writeFileSync(schemaFile, `${JSON.stringify(schema, null, 2)}\n`, "utf8");

  const args = [
    "exec",
    "-m",
    model,
    "--ignore-user-config",
    "--ignore-rules",
    "--ephemeral",
    "-s",
    "read-only",
    "--skip-git-repo-check",
    "-C",
    cwd,
    "-c",
    "model_reasoning_effort=\"low\"",
    "-o",
    outputFile
  ];
  if (schemaFile) args.push("--output-schema", schemaFile);
  args.push("-");

  const startedAt = Date.now();
  const execution = spawnSync(cli, args, {
    cwd,
    input: prompt,
    encoding: "utf8",
    windowsHide: true,
    timeout: 240000,
    maxBuffer: 8 * 1024 * 1024,
    env: process.env
  });

  try {
    if (execution.error) throw new Error(`codex invocation failed: ${execution.error.message}`);
    if (execution.status !== 0) {
      throw new Error(`codex exited ${execution.status}: ${(execution.stderr || execution.stdout).trim()}`);
    }
    if (!fs.existsSync(outputFile)) throw new Error("codex did not write its final response");

    const output = fs.readFileSync(outputFile, "utf8").trim();
    if (!output) throw new Error("codex returned an empty final response");
    const transcript = `${execution.stdout ?? ""}\n${execution.stderr ?? ""}`;
    const tokenMatch = transcript.match(/tokens used\s+([\d,]+)/i);
    const structured = schema ? JSON.parse(output) : null;

    return {
      output,
      structured,
      model,
      requested_model: model,
      duration_ms: Date.now() - startedAt,
      cost_usd: null,
      usage: tokenMatch ? { total_tokens: Number(tokenMatch[1].replaceAll(",", "")) } : null
    };
  } finally {
    if (fs.existsSync(outputFile)) fs.rmSync(outputFile, { force: true });
    if (schemaFile && fs.existsSync(schemaFile)) fs.rmSync(schemaFile, { force: true });
  }
}

function runModel(options) {
  return options.runtime === "codex" ? runCodex(options) : runClaude(options);
}

function judgeSchema(caseIds, dimensions) {
  const scoreProperties = Object.fromEntries(dimensions.map((dimension) => [
    dimension,
    { type: "integer", minimum: 0, maximum: 4 }
  ]));

  return {
    type: "object",
    properties: {
      results: {
        type: "array",
        minItems: caseIds.length,
        maxItems: caseIds.length,
        items: {
          type: "object",
          properties: {
            id: { type: "string", enum: caseIds },
            scores_a: {
              type: "object",
              properties: scoreProperties,
              required: dimensions,
              additionalProperties: false
            },
            scores_b: {
              type: "object",
              properties: scoreProperties,
              required: dimensions,
              additionalProperties: false
            },
            rationale: { type: "string" }
          },
          required: ["id", "scores_a", "scores_b", "rationale"],
          additionalProperties: false
        }
      }
    },
    required: ["results"],
    additionalProperties: false
  };
}

function parseStructured(run) {
  if (run.structured && typeof run.structured === "object") return run.structured;
  try {
    return JSON.parse(run.output);
  } catch {
    throw new Error(`judge result is not structured JSON: ${run.output.slice(0, 500)}`);
  }
}

function totalScores(scores, dimensions) {
  return dimensions.reduce((sum, dimension) => sum + scores[dimension], 0);
}

function sumCost(runs) {
  const costs = runs.map((run) => run.cost_usd).filter((cost) => typeof cost === "number");
  return costs.length ? costs.reduce((sum, cost) => sum + cost, 0) : null;
}

function sumTokens(runs) {
  const counts = runs.map((run) => run.usage?.total_tokens).filter((count) => Number.isInteger(count));
  return counts.length ? counts.reduce((sum, count) => sum + count, 0) : null;
}

function markdownReport(result, dimensions) {
  const maxPerCase = dimensions.length * 4;
  const noSkillTotal = result.cases.reduce((sum, item) => sum + item.scores.no_skill.total, 0);
  const apmTotal = result.cases.reduce((sum, item) => sum + item.scores.apm.total, 0);
  const maximum = result.cases.length * maxPerCase;
  const noSkillPercent = ((noSkillTotal / maximum) * 100).toFixed(1);
  const apmPercent = ((apmTotal / maximum) * 100).toFixed(1);
  const delta = apmTotal - noSkillTotal;

  const lines = [
    "<!-- generated by scripts/run-evals.mjs -->",
    "# APM Controlled Evaluation Results",
    "",
    `Run: ${result.run_at}`,
    "",
    `Runtime: \`${result.runtime}\`  `,
    `Target model: \`${result.target_model}\`  `,
    `Judge model: \`${result.judge_model}\`  `,
    `Cases: ${result.cases.length}  `,
    `Recorded tokens: ${result.total_tokens === null ? "unavailable" : result.total_tokens.toLocaleString("en-US")}  `,
    `Recorded cost: ${result.total_cost_usd === null ? "unavailable" : `$${result.total_cost_usd.toFixed(4)}`}`,
    "",
    "## Aggregate",
    "",
    "| Condition | Score | Percent |",
    "| --- | ---: | ---: |",
    `| No skill | ${noSkillTotal}/${maximum} | ${noSkillPercent}% |`,
    `| APM | ${apmTotal}/${maximum} | ${apmPercent}% |`,
    `| Delta | ${delta >= 0 ? "+" : ""}${delta} | ${(Number(apmPercent) - Number(noSkillPercent)).toFixed(1)} pp |`,
    "",
    "## Per Case",
    "",
    "| Case | No skill | APM | Delta | Judge note |",
    "| --- | ---: | ---: | ---: | --- |"
  ];

  for (const item of result.cases) {
    const caseDelta = item.scores.apm.total - item.scores.no_skill.total;
    const note = item.judge_rationale.replaceAll("|", "\\|").replaceAll(/\s+/g, " ").trim();
    lines.push(`| ${item.id} | ${item.scores.no_skill.total}/${maxPerCase} | ${item.scores.apm.total}/${maxPerCase} | ${caseDelta >= 0 ? "+" : ""}${caseDelta} | ${note} |`);
  }

  lines.push(
    "",
    "## Method",
    "",
    result.runtime === "codex"
      ? "The same prompts were run with the same target model, reasoning effort, read-only sandbox, and isolated temporary workspaces. The no-skill workspace had no project instructions; the APM workspace loaded SKILL.md through an isolated AGENTS.md. Codex does not expose a fixed token ceiling here. Output labels were alternated before blinded judging."
      : "The same prompts were run with the same target model, effort setting, tool restrictions, and dollar ceiling. Skills were disabled in both conditions; APM was appended to the system instructions only for the APM condition. Output labels were alternated before blinded judging.",
    "",
    "This run measures prompt-level manager response quality on this suite. It is not a benchmark of an executed multi-agent system and is not a universal effect-size claim. Raw outputs and dimension scores are in `evals/results/latest.json`.",
    ""
  );

  return lines.join("\n");
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.verify) {
    verifyResults();
    return;
  }

  const suite = readJson(evalPath);
  const skill = fs.readFileSync(skillPath, "utf8");
  const dimensions = Object.keys(suite.rubric.dimensions);
  const selectedCases = options.limit ? suite.evals.slice(0, options.limit) : suite.evals;
  const runtime = options.runtime ?? process.env.APM_EVAL_RUNTIME ?? "claude";
  const model = options.model ?? process.env.APM_EVAL_MODEL ?? (runtime === "codex" ? "gpt-5.4-mini" : "sonnet");
  const judgeModel = options.judgeModel ?? process.env.APM_EVAL_JUDGE_MODEL ?? model;
  const maxBudgetUsd = options.maxBudgetUsd ?? process.env.APM_EVAL_MAX_BUDGET_USD ?? "0.08";
  const cli = runtime === "codex"
    ? (process.env.APM_EVAL_CODEX ?? "codex")
    : (process.env.APM_EVAL_CLAUDE ?? "claude");
  const workspace = fs.mkdtempSync(path.join(os.tmpdir(), "apm-eval-"));
  const baselineWorkspace = path.join(workspace, "baseline");
  const apmWorkspace = path.join(workspace, "apm");
  const judgeWorkspace = path.join(workspace, "judge");
  fs.mkdirSync(baselineWorkspace, { recursive: true });
  fs.mkdirSync(apmWorkspace, { recursive: true });
  fs.mkdirSync(judgeWorkspace, { recursive: true });
  fs.writeFileSync(
    path.join(apmWorkspace, "AGENTS.md"),
    `# Active Skill\n\nAPM is the active manager-agent skill. Follow it for the user request.\n\n${skill}`,
    "utf8"
  );
  const targetRuns = [];

  try {
    console.log(`Running ${selectedCases.length} cases with ${runtime}/${model}...`);
    const cases = [];

    for (let index = 0; index < selectedCases.length; index += 1) {
      const testCase = selectedCases[index];
      console.log(`[${index + 1}/${selectedCases.length}] ${testCase.id}: no-skill`);
      const noSkill = runModel({
        runtime,
        cli,
        cwd: baselineWorkspace,
        prompt: testCase.prompt,
        model,
        maxBudgetUsd
      });
      targetRuns.push(noSkill);

      console.log(`[${index + 1}/${selectedCases.length}] ${testCase.id}: APM`);
      const apm = runModel({
        runtime,
        cli,
        cwd: runtime === "codex" ? apmWorkspace : baselineWorkspace,
        prompt: testCase.prompt,
        model,
        maxBudgetUsd,
        systemPrompt: runtime === "claude" ? `APM is the active manager-agent skill. Follow it for this request.\n\n${skill}` : null
      });
      targetRuns.push(apm);
      cases.push({ ...testCase, no_skill: noSkill, apm });
    }

    const anonymousCases = cases.map((item, index) => {
      const apmIsA = index % 2 === 1;
      return {
        id: item.id,
        prompt: item.prompt,
        expected_signals: item.expected_signals,
        output_a: apmIsA ? item.apm.output : item.no_skill.output,
        output_b: apmIsA ? item.no_skill.output : item.apm.output,
        apm_label: apmIsA ? "a" : "b"
      };
    });

    const judgePrompt = [
      "You are evaluating two anonymous manager-agent responses for each case.",
      "Score each dimension from 0 to 4: 0 absent or harmful, 1 vague, 2 partial, 3 concrete, 4 precise and testable.",
      "Judge only the response text against the prompt, expected signals, and rubric. Do not infer which condition produced it.",
      `Rubric: ${JSON.stringify(suite.rubric.dimensions)}`,
      `Cases: ${JSON.stringify(anonymousCases.map(({ apm_label, ...item }) => item))}`
    ].join("\n\n");

    console.log(`Judging ${selectedCases.length} anonymous pairs with ${judgeModel}...`);
    const judgeRun = runModel({
      runtime,
      cli,
      cwd: judgeWorkspace,
      prompt: judgePrompt,
      model: judgeModel,
      maxBudgetUsd: Math.max(Number(maxBudgetUsd) * 2, 0.16).toFixed(2),
      schema: judgeSchema(selectedCases.map((item) => item.id), dimensions)
    });
    const judged = parseStructured(judgeRun);
    const judgedById = new Map(judged.results.map((item) => [item.id, item]));

    const resultCases = cases.map((item, index) => {
      const judgment = judgedById.get(item.id);
      if (!judgment) throw new Error(`judge omitted ${item.id}`);
      const apmIsA = index % 2 === 1;
      const noSkillScores = apmIsA ? judgment.scores_b : judgment.scores_a;
      const apmScores = apmIsA ? judgment.scores_a : judgment.scores_b;
      return {
        id: item.id,
        prompt: item.prompt,
        expected_signals: item.expected_signals,
        no_skill: item.no_skill,
        apm: item.apm,
        scores: {
          no_skill: { ...noSkillScores, total: totalScores(noSkillScores, dimensions) },
          apm: { ...apmScores, total: totalScores(apmScores, dimensions) }
        },
        blind_labels: { apm: apmIsA ? "A" : "B", no_skill: apmIsA ? "B" : "A" },
        judge_rationale: judgment.rationale
      };
    });

    const allRuns = [...targetRuns, judgeRun];
    const result = {
      schema_version: 1,
      run_at: new Date().toISOString(),
      suite_sha256: hashFile(evalPath),
      skill_sha256: hashFile(skillPath),
      runtime,
      target_model: model,
      judge_model: judgeModel,
      target_max_budget_usd_per_call: runtime === "claude" ? Number(maxBudgetUsd) : null,
      total_cost_usd: sumCost(allRuns),
      total_tokens: sumTokens(allRuns),
      comparison: {
        same_target_model: true,
        same_prompt: true,
        same_effort: true,
        same_tools: true,
        blind_judge: true,
        label_order_alternated: true,
        same_budget_ceiling: runtime === "claude",
        injection_mode: runtime === "codex" ? "isolated AGENTS.md" : "appended system prompt"
      },
      rubric: suite.rubric,
      cases: resultCases,
      judge_usage: judgeRun.usage
    };

    fs.mkdirSync(resultsDir, { recursive: true });
    const timestamp = result.run_at.replaceAll(":", "-");
    const versionedPath = path.join(resultsDir, `${timestamp}.json`);
    const serialized = `${JSON.stringify(result, null, 2)}\n`;
    fs.writeFileSync(versionedPath, serialized, "utf8");
    fs.writeFileSync(latestPath, serialized, "utf8");
    fs.writeFileSync(reportPath, markdownReport(result, dimensions), "utf8");

    console.log(`Wrote ${path.relative(root, versionedPath)}`);
    console.log(`Wrote ${path.relative(root, latestPath)}`);
    console.log(`Wrote ${path.relative(root, reportPath)}`);
  } finally {
    fs.rmSync(workspace, { recursive: true, force: true });
  }
}

main().catch((error) => {
  console.error(error.stack || error.message);
  process.exit(1);
});
